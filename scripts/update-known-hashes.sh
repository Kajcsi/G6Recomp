#!/usr/bin/env bash
# Adds the SHA-256 of every file up to 2 MiB in a game install to scripts/known-game-hashes.txt,
# so check-clean.sh can reject copies of them. Larger files are already rejected by size.
# Only the hashes are recorded: no file content, and no file names (a listing of the install is
# itself derived from the game, so it stays local).
#
# Usage: scripts/update-known-hashes.sh <game-dir>
set -euo pipefail

if [[ $# -ne 1 || ! -d $1 ]]; then
    echo "usage: $0 <game-dir>" >&2
    exit 2
fi

repo_root=$(git rev-parse --show-toplevel)
list="$repo_root/scripts/known-game-hashes.txt"
game_dir=$1
max_bytes=$((2 * 1024 * 1024))

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
[[ -f $list ]] && grep -oE '^[0-9a-f]{64}' "$list" >"$tmp" || true

while IFS= read -r -d '' file; do
    sha256sum "$file" | cut -d' ' -f1 >>"$tmp"
done < <(find "$game_dir" -type f -size -$((max_bytes + 1))c -print0)

{
    echo "# SHA-256 of game files up to 2 MiB. Generated by scripts/update-known-hashes.sh."
    echo "# check-clean.sh rejects any committed file with one of these hashes."
    sort -u "$tmp"
} >"$list"
echo "$(grep -cE '^[0-9a-f]{64}' "$list") hashes in ${list#"$repo_root"/}"
