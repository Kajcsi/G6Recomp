class Rng {
public:
    explicit Rng(uint64_t seed) : state_((seed * 0x9e3779b97f4a7c15ull) | 1) {}

    uint64_t next() {
        state_ ^= state_ << 13;
        state_ ^= state_ >> 7;
        state_ ^= state_ << 17;
        return state_;
    }
    uint64_t below(uint64_t n) { return next() % n; }

private:
    uint64_t state_;
};

// Boundary values for every operand width.
constexpr uint64_t kInteresting[] = {
    0,
    1,
    2,
    3,
    0x7f,
    0x80,
    0xff,
    0x100,
    0x7fff,
    0x8000,
    0xffff,
    0x10000,
    0x7fffffff,
    0x80000000,
    0xffffffff,
    0x100000000,
    0x7fffffffffffffff,
    0x8000000000000000,
    0xffffffffffffffff,
    0xfffffffffffffffe,
    0x0123456789abcdef,
    0xfedcba9876543210,
    0x5555555555555555,
    0xaaaaaaaaaaaaaaaa,
    0xffffffff00000000,
    0x00000000ffff0000,
    0x8000000080008080,
    0x0000000100000001,
};

uint64_t pick(Rng& rng) {
    const uint64_t value = kInteresting[rng.below(std::size(kInteresting))];
    switch (rng.below(4)) {
    case 0: return value;
    case 1: {
        // A boundary value in the low 8, 16, or 32 bits, with garbage above it.
        const uint64_t mask = (uint64_t{1} << (8u << rng.below(3))) - 1;
        return (rng.next() & ~mask) | (value & mask);
    }
    case 2: return rng.next() >> rng.below(64);
    default: return rng.next();
    }
}

constexpr uint32_t kFloatBits[] = {
    0x00000000, 0x80000000, 0x3f800000, 0xbfc00000, 0x7f800000, 0xff800000, 0x7fc00000,
    0x7fa00000, 0x00000001, 0x007fffff, 0x7f7fffff, 0x4f000000, 0xcf000000, 0x3f000000,
    0x40490fdb, 0x3fc00000, 0x40200000, 0xc0200000, 0x4b000000, 0x5f000000, 0xdf000000,
};

constexpr uint64_t kDoubleBits[] = {
    0x0000000000000000, 0x8000000000000000, 0x3ff0000000000000, 0xbff8000000000000,
    0x7ff0000000000000, 0xfff0000000000000, 0x7ff8000000000000, 0x7ff4000000000000,
    0x0000000000000001, 0x7fefffffffffffff, 0x41e0000000000000, 0xc1e0000000200000,
    0x43e0000000000000, 0xc3e0000000000000, 0x3fe0000000000000, 0x4004000000000000,
    0xc004000000000000, 0x7e37e43c8800759c, 0x4330000000000000, 0x43f0000000000000,
};

float pick_float(Rng& rng) {
    if (rng.below(2) == 0) {
        return std::bit_cast<float>(kFloatBits[rng.below(std::size(kFloatBits))]);
    }
    return static_cast<float>(static_cast<int64_t>(rng.next())) /
           static_cast<float>(uint64_t{1} << rng.below(64));
}

double pick_double(Rng& rng) {
    if (rng.below(2) == 0) {
        return std::bit_cast<double>(kDoubleBits[rng.below(std::size(kDoubleBits))]);
    }
    return static_cast<double>(static_cast<int64_t>(rng.next())) /
           static_cast<double>(uint64_t{1} << rng.below(64));
}

// Vector inputs: a mix of integer patterns, small lanes, and special float and double values.
void fill_vector(std::span<uint8_t> out, Rng& rng) {
    for (size_t i = 0; i < out.size(); i += 8) {
        uint64_t value = 0;
        switch (rng.below(6)) {
        case 0: value = rng.next(); break;
        case 1:
            value = kFloatBits[rng.below(std::size(kFloatBits))] |
                    uint64_t{kFloatBits[rng.below(std::size(kFloatBits))]} << 32;
            break;
        case 2: value = kDoubleBits[rng.below(std::size(kDoubleBits))]; break;
        case 3:
            for (int lane = 0; lane < 4; ++lane) {
                value |= ((rng.below(48) - 24) & 0xffff) << (16 * lane);
            }
            break;
        case 4: value = pick(rng); break;
        default:
            for (int lane = 0; lane < 8; ++lane) {
                constexpr uint8_t kBytes[] = {0x00, 0x01, 0x7f, 0x80, 0x81, 0xfe, 0xff, 0x10};
                value |= uint64_t{kBytes[rng.below(std::size(kBytes))]} << (8 * lane);
            }
            break;
        }
        std::memcpy(out.data() + i, &value, std::min(sizeof(value), out.size() - i));
    }
}

template <typename T>
std::vector<T> random_values(Rng& rng, size_t count) {
    std::vector<T> values(count);
    for (T& value : values) {
        if constexpr (std::is_same_v<T, float>) {
            value = pick_float(rng);
        } else if constexpr (std::is_same_v<T, double>) {
            value = pick_double(rng);
        } else {
            value = static_cast<T>(pick(rng));
        }
    }
    return values;
}

