// Differential tests for the recompiler. The test program in programs/ is an original DLL built
// from C and hand-written assembly, twice (baseline SSE2 and /arch:AVX2); the build runs
// x64recomp on each build and links the generated code in here. Every test calls an exported
// function natively (the DLL loaded with LoadLibrary) and recompiled (the same image mapped at
// its assigned base and run through g6::cpu::invoke) with the same inputs, and checks that the
// return value, the memory written, and the status flags the instruction defines all match.
// Each recompiled call also has to keep the Win64 callee-saved registers and balance the stack.
//
// Not covered yet: guest exceptions and TLS, which wait for their runtime models (see
// docs/codegen.md).

