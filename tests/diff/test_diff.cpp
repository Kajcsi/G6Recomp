// ---- Reporting ------------------------------------------------------------------------------

std::vector<std::string> g_mismatches;

// One mismatch. The first few are reported in detail; summarize() lists them all.
void mismatch(std::string_view program, std::string_view what, const std::string& detail) {
    g_mismatches.push_back(fmt::format("{}:{}", program, what));
    if (g_mismatches.size() <= 20) {
        g6::test::report_failure(__FILE__, __LINE__,
                                 fmt::format("{}: {}: {}", program, what, detail));
    }
}

// Reports every mismatch since `first` by name, for when there are too many to show in full.
void summarize(size_t first) {
    if (g_mismatches.size() - first <= 1) {
        return;
    }
    std::string names;
    for (size_t i = first; i < g_mismatches.size(); ++i) {
        names += (i == first ? "" : ", ") + g_mismatches[i];
    }
    g6::test::report_failure(__FILE__, __LINE__,
                             fmt::format("{} mismatches: {}", g_mismatches.size() - first, names));
}

std::string hex(const void* data, size_t size) {
    std::string text;
    const auto* bytes = static_cast<const uint8_t*>(data);
    for (size_t i = 0; i < size; ++i) {
        text += fmt::format("{}{:02x}", i > 0 && i % 8 == 0 ? " " : "", bytes[i]);
    }
    return text;
}

template <typename T>
std::string show(const T& value) {
    if constexpr (std::is_pointer_v<T>) {
        return fmt::format("{}", static_cast<const void*>(value));
    } else if constexpr (std::is_floating_point_v<T>) {
        using Bits = std::conditional_t<sizeof(T) == 4, uint32_t, uint64_t>;
        return fmt::format("{} [{:#x}]", value, std::bit_cast<Bits>(value));
    } else if constexpr (std::is_integral_v<T>) {
        return fmt::format("{:#x}", value);
    } else {
        return hex(&value, sizeof(value));
    }
}

template <typename... A>
std::string show_all(const A&... values) {
    std::string text;
    ((text += (text.empty() ? "" : ", ") + show(values)), ...);
    return text;
}

