struct Triple {
    int64_t a;
    int64_t b;
    int64_t c;
};

// A divisor that keeps every division in c_divide defined.
int64_t safe_divisor(Rng& rng) {
    for (;;) {
        const auto b = static_cast<int64_t>(pick(rng));
        const auto low = static_cast<int32_t>(b);
        if (b != 0 && b != -1 && low != 0 && low != -1) {
            return b;
        }
    }
}

void integer_code(const Program& program) {
    Rng rng(0x1d1);
    std::vector<uint8_t> bytes(512);
    fill_vector(bytes, rng);

    for (int i = 0; i < 64; ++i) {
        const uint64_t size = rng.below(bytes.size());
        if (!compare_call<uint64_t>(program, "c_hash", static_cast<const uint8_t*>(bytes.data()),
                                    size, pick(rng))) {
            break;
        }
    }
    for (int i = 0; i < 256; ++i) {
        const auto a = static_cast<int64_t>(pick(rng));
        const int64_t b = safe_divisor(rng);
        const bool ok =
            compare_buffers<int64_t>(program, "c_divide", std::vector<int64_t>(12, 0x7777),
                                     show_all(a, b), [&](Side side, int64_t* out) {
                                         call<void>(side, program, "c_divide", a, b, out);
                                         return uint64_t{0};
                                     });
        if (!ok) {
            break;
        }
    }
    for (int64_t selector = -3; selector < 16; ++selector) {
        for (int i = 0; i < 8; ++i) {
            if (!compare_call<int64_t>(program, "c_switch", selector,
                                       static_cast<int64_t>(pick(rng)))) {
                break;
            }
        }
    }
    for (uint32_t n = 0; n < 22; ++n) {
        compare_call<uint64_t>(program, "c_fib", n);
    }
    for (int i = 0; i < 64; ++i) {
        const uint64_t which = rng.below(16);
        const auto a = static_cast<int64_t>(pick(rng));
        const auto b = static_cast<int64_t>(pick(rng));
        compare_call<int64_t>(program, "c_dispatch", which, a, b);
        compare_call<int64_t>(program, "c_dispatch_all", which, a, b);
    }
    for (int i = 0; i < 64; ++i) {
        if (!compare_call<uint64_t>(program, "c_tail_chain", pick(rng),
                                    static_cast<uint32_t>(rng.below(200)))) {
            break;
        }
    }
    for (int i = 0; i < 48; ++i) {
        const size_t count = rng.below(200);
        std::vector<int32_t> values(count);
        for (int32_t& value : values) {
            value = rng.below(4) == 0 ? static_cast<int32_t>(rng.below(8))
                                      : static_cast<int32_t>(pick(rng));
        }
        const bool ok =
            compare_buffers<int32_t>(program, "c_sort", values, fmt::format("count {}", count),
                                     [&](Side side, int32_t* data) {
                                         call<void>(side, program, "c_sort", data, count);
                                         return uint64_t{0};
                                     });
        if (!ok) {
            break;
        }
    }
    for (int i = 0; i < 48; ++i) {
        const size_t size = rng.below(300);
        const auto value = static_cast<int32_t>(pick(rng));
        std::vector<uint8_t> initial(300);
        fill_vector(initial, rng);
        const bool ok = compare_buffers<uint8_t>(
            program, "c_fill_copy", initial, fmt::format("size {}", size),
            [&](Side side, uint8_t* dst) {
                call<void>(side, program, "c_fill_copy", dst,
                           static_cast<const uint8_t*>(bytes.data()), size, value);
                return uint64_t{0};
            });
        if (!ok) {
            break;
        }
    }
    for (int i = 0; i < 32; ++i) {
        compare_call<uint32_t>(program, "c_histogram", static_cast<const uint8_t*>(bytes.data()),
                               static_cast<size_t>(rng.below(bytes.size())));
    }
    for (int i = 0; i < 32; ++i) {
        // Each side has its own copy of the global; the same calls keep them in step.
        compare_call<int64_t>(program, "c_counter", static_cast<int64_t>(pick(rng)));
    }
    for (int i = 0; i < 512; ++i) {
        if (!compare_call<uint64_t>(program, "c_bits", pick(rng), pick(rng))) {
            break;
        }
    }
    for (int i = 0; i < 256; ++i) {
        const uint64_t a = pick(rng);
        const uint64_t b = pick(rng);
        const bool ok = compare_buffers<uint64_t>(program, "c_mul128", std::vector<uint64_t>(6, 0),
                                                  show_all(a, b), [&](Side side, uint64_t* out) {
                                                      return call<uint64_t>(side, program,
                                                                            "c_mul128", a, b, out);
                                                  });
        if (!ok) {
            break;
        }
    }
    for (int i = 0; i < 64; ++i) {
        const bool ok = compare_call<double>(
            program, "c_many_args", static_cast<int64_t>(rng.next() >> 20), pick_double(rng),
            static_cast<int32_t>(pick(rng)), pick_float(rng), static_cast<int64_t>(pick(rng)),
            pick_double(rng), static_cast<int8_t>(pick(rng)), static_cast<uint16_t>(pick(rng)),
            pick_float(rng));
        if (!ok) {
            break;
        }
    }
    for (int i = 0; i < 32; ++i) {
        compare_call<Triple>(program, "c_struct_return", static_cast<int64_t>(pick(rng)),
                             static_cast<int64_t>(pick(rng)));
    }
}

void floating_point(const Program& program) {
    Rng rng(0xf10a7);
    for (int i = 0; i < 512; ++i) {
        const bool ok =
            compare_call<double>(program, "c_float_mix", pick_double(rng), pick_double(rng),
                                 static_cast<int64_t>(pick(rng))) &&
            compare_call<float>(program, "c_float_math", pick_float(rng), pick_float(rng),
                                static_cast<int32_t>(pick(rng))) &&
            compare_call<int32_t>(program, "c_float_compare", pick_double(rng), pick_double(rng));
        if (!ok) {
            break;
        }
    }
}

void vectorized_loops(const Program& program) {
    Rng rng(0x5eed);
    for (int i = 0; i < 64; ++i) {
        const size_t n = rng.below(100);
        const std::vector<int32_t> a = random_values<int32_t>(rng, n);
        const std::vector<int32_t> b = random_values<int32_t>(rng, n);
        const std::vector<uint8_t> bytes = random_values<uint8_t>(rng, n);
        const std::vector<int16_t> shorts = random_values<int16_t>(rng, n);
        const std::vector<uint16_t> ushorts = random_values<uint16_t>(rng, n);
        const std::vector<float> floats = random_values<float>(rng, n);
        const std::vector<double> doubles = random_values<double>(rng, n);
        const std::string args = fmt::format("n {}", n);

        compare_call<int64_t>(program, "c_dot_i32", a.data(), b.data(), n);
        compare_call<uint32_t>(program, "c_byte_sum", bytes.data(), n);
        compare_call<size_t>(program, "c_count_if", a.data(), n, static_cast<int32_t>(pick(rng)));

        const float scale = pick_float(rng);
        compare_buffers<float>(program, "c_saxpy", random_values<float>(rng, n), args,
                               [&](Side side, float* y) {
                                   call<void>(side, program, "c_saxpy", scale, floats.data(), y, n);
                                   return uint64_t{0};
                               });
        const double factor = pick_double(rng);
        compare_buffers<double>(
            program, "c_scale_f64", std::vector<double>(n), args, [&](Side side, double* out) {
                call<void>(side, program, "c_scale_f64", out, doubles.data(), n, factor);
                return uint64_t{0};
            });
        compare_buffers<int16_t>(program, "c_minmax", std::vector<int16_t>(2), args,
                                 [&](Side side, int16_t* out) {
                                     call<void>(side, program, "c_minmax", shorts.data(), n, out);
                                     return uint64_t{0};
                                 });
        compare_buffers<uint8_t>(program, "c_clamp_bytes", std::vector<uint8_t>(n), args,
                                 [&](Side side, uint8_t* out) {
                                     call<void>(side, program, "c_clamp_bytes", a.data(), out, n);
                                     return uint64_t{0};
                                 });
        compare_buffers<int64_t>(program, "c_widen", std::vector<int64_t>(n), args,
                                 [&](Side side, int64_t* out) {
                                     call<void>(side, program, "c_widen", ushorts.data(), out, n);
                                     return uint64_t{0};
                                 });
        compare_buffers<int32_t>(
            program, "c_float_to_int", std::vector<int32_t>(n), args, [&](Side side, int32_t* out) {
                call<void>(side, program, "c_float_to_int", floats.data(), out, n);
                return uint64_t{0};
            });
    }
}

// ---- CPU identification -------------------------------------------------------------------

// Recompiled code sees the console's CPU: the host's features, limited to those Zen 2 also has
// (g6/cpu/cpuid.h). So these checks compare the recompiled answer with the native one through
// that rule, written out here from the architecture's bit assignments, not from the runtime.

struct Cpuid {
    uint32_t eax = 0;
    uint32_t ebx = 0;
    uint32_t ecx = 0;
    uint32_t edx = 0;
};

Cpuid cpuid_on(Side side, const Program& program, uint32_t leaf, uint32_t subleaf) {
    std::array<uint32_t, 4> r{};
    call<void>(side, program, "c_cpuid", leaf, subleaf, r.data());
    return {r[0], r[1], r[2], r[3]};
}

constexpr uint32_t bits(std::initializer_list<unsigned> positions) {
    uint32_t mask = 0;
    for (const unsigned position : positions) {
        mask |= uint32_t{1} << position;
    }
    return mask;
}

// Every bit of `guest` is set in `native` too.
bool within(uint32_t guest, uint32_t native) {
    return (guest & ~native) == 0;
}

// Bits Zen 2 has: the recompiled answer has them exactly when the host does.
bool kept(uint32_t guest, uint32_t native, uint32_t mask) {
    return (guest & mask) == (native & mask);
}

void cpu_identification(const Program& program) {
    // `rule` returns what's wrong, or nullptr.
    const auto check = [&](uint32_t leaf, uint32_t subleaf, auto&& rule) {
        const Cpuid n = cpuid_on(Side::kNative, program, leaf, subleaf);
        const Cpuid g = cpuid_on(Side::kGuest, program, leaf, subleaf);
        if (const char* problem = rule(n, g); problem != nullptr) {
            mismatch(program.name(), "c_cpuid",
                     fmt::format("leaf {:#x}.{}: {} (native {:08x} {:08x} {:08x} {:08x}, "
                                 "recompiled {:08x} {:08x} {:08x} {:08x})",
                                 leaf, subleaf, problem, n.eax, n.ebx, n.ecx, n.edx, g.eax, g.ebx,
                                 g.ecx, g.edx));
        }
    };
    const auto zero = [](const Cpuid&, const Cpuid& g) -> const char* {
        return g.eax == 0 && g.ebx == 0 && g.ecx == 0 && g.edx == 0 ? nullptr : "not all zero";
    };

    check(0, 0, [](const Cpuid& n, const Cpuid& g) -> const char* {
        if (g.eax != std::min(n.eax, 0x10u)) {
            return "highest leaf isn't capped at Zen 2's 0x10";
        }
        return g.ebx == n.ebx && g.ecx == n.ecx && g.edx == n.edx ? nullptr : "vendor changed";
    });
    check(1, 0, [](const Cpuid& n, const Cpuid& g) -> const char* {
        // EBX bits 24-31 are the APIC ID of whichever core ran the instruction.
        if (g.eax != n.eax || (g.ebx & 0xffffff) != (n.ebx & 0xffffff) || g.edx != n.edx) {
            return "family, model, or baseline features changed";
        }
        if (!within(g.ecx, n.ecx) || (g.ecx & bits({31})) != 0) {
            return "ECX reports a feature the host lacks, or a hypervisor";
        }
        // SSE3, SSSE3, FMA, SSE4.1, SSE4.2, MOVBE, POPCNT, AES, OSXSAVE, AVX, F16C.
        return kept(g.ecx, n.ecx, bits({0, 9, 12, 19, 20, 22, 23, 25, 27, 28, 29}))
                   ? nullptr
                   : "ECX dropped a Zen 2 feature";
    });
    check(7, 0, [](const Cpuid& n, const Cpuid& g) -> const char* {
        if (g.eax != 0 || g.edx != 0 || !within(g.ebx, n.ebx) || !within(g.ecx, n.ecx)) {
            return "reports subleaves, EDX features, or features the host lacks";
        }
        // AVX-512 F, DQ, IFMA, PF, ER, CD, BW, VL, and ERMS.
        if ((g.ebx & bits({9, 16, 17, 21, 26, 27, 28, 30, 31})) != 0) {
            return "EBX reports a feature Zen 2 lacks";
        }
        // AVX-512 VBMI, VBMI2, VNNI, BITALG, VPOPCNTDQ, and GFNI, VAES, VPCLMULQDQ.
        if ((g.ecx & bits({1, 6, 8, 9, 10, 11, 12, 14})) != 0) {
            return "ECX reports a feature Zen 2 lacks";
        }
        // BMI1, AVX2, BMI2, ADX, SHA.
        return kept(g.ebx, n.ebx, bits({3, 5, 8, 19, 29})) ? nullptr
                                                           : "EBX dropped a Zen 2 feature";
    });
    check(7, 1, zero);
    check(0xd, 0, [](const Cpuid& n, const Cpuid& g) -> const char* {
        return g.eax == (n.eax & 7) && g.edx == 0 && g.ebx == n.ebx && g.ecx == n.ecx
                   ? nullptr
                   : "state components other than x87, SSE, and AVX";
    });
    check(0xd, 1, [](const Cpuid& n, const Cpuid& g) -> const char* {
        return within(g.eax, n.eax & 0xf) ? nullptr : "XSAVE variants beyond Zen 2's";
    });
    check(0xd, 2, [](const Cpuid& n, const Cpuid& g) -> const char* {
        return g.eax == n.eax && g.ebx == n.ebx ? nullptr : "AVX state layout changed";
    });
    check(0xd, 5, zero);        // AVX-512 opmask state
    check(0x14, 0, zero);       // past Zen 2's highest leaf
    check(0x40000000, 0, zero); // hypervisor information
    check(0x80000000, 0, [](const Cpuid& n, const Cpuid& g) -> const char* {
        return g.eax == n.eax ? nullptr : "highest extended leaf changed";
    });
    check(0x80000001, 0, [](const Cpuid& n, const Cpuid& g) -> const char* {
        if (g.edx != n.edx || !within(g.ecx, n.ecx)) {
            return "EDX changed, or ECX reports a feature the host lacks";
        }
        // XOP, FMA4, TBM.
        if ((g.ecx & bits({11, 16, 21})) != 0) {
            return "ECX reports a feature Zen 2 lacks";
        }
        // LAHF/SAHF, LZCNT, PREFETCHW.
        return kept(g.ecx, n.ecx, bits({0, 5, 8})) ? nullptr : "ECX dropped a Zen 2 feature";
    });

    const auto native_xcr0 = call<uint64_t>(Side::kNative, program, "c_xgetbv", uint32_t{0});
    const auto guest_xcr0 = call<uint64_t>(Side::kGuest, program, "c_xgetbv", uint32_t{0});
    if (guest_xcr0 != (native_xcr0 & 7)) {
        mismatch(program.name(), "c_xgetbv",
                 fmt::format("XCR0 is {:#x} natively, {:#x} recompiled; expected only x87, SSE, "
                             "and AVX state",
                             native_xcr0, guest_xcr0));
    }

    // Natively this returns the shadow stack pointer if the host process has one.
    const auto guest_ssp = call<uint64_t>(Side::kGuest, program, "c_rdssp");
    if (guest_ssp != 0) {
        mismatch(program.name(), "c_rdssp",
                 fmt::format("rdsspq returned {:#x} recompiled; expected no shadow stack (0)",
                             guest_ssp));
    }
}

