constexpr uint64_t kSse2Base = 0x1000000000;
constexpr uint64_t kAvx2Base = 0x1010000000;

// Both the native and the recompiled runs execute these on the host.
bool host_has_required_features() {
    std::array<int, 4> r{};
    __cpuid(r.data(), 0);
    if (r[0] < 7) {
        return false;
    }
    __cpuid(r.data(), 1);
    const auto ecx1 = static_cast<uint32_t>(r[2]);
    __cpuidex(r.data(), 7, 0);
    const auto ebx7 = static_cast<uint32_t>(r[1]);
    __cpuid(r.data(), static_cast<int>(0x80000001));
    const auto ecx_ext = static_cast<uint32_t>(r[2]);
    const auto has = [](uint32_t reg, int bit) { return ((reg >> bit) & 1) != 0; };
    return has(ecx1, 12) /* FMA */ && has(ecx1, 19) /* SSE4.1 */ && has(ecx1, 20) /* SSE4.2 */ &&
           has(ecx1, 22) /* MOVBE */ && has(ecx1, 23) /* POPCNT */ && has(ecx1, 27) /* OSXSAVE */ &&
           has(ecx1, 28) /* AVX */ && has(ebx7, 3) /* BMI1 */ && has(ebx7, 5) /* AVX2 */ &&
           has(ebx7, 8) /* BMI2 */ && has(ecx_ext, 5) /* LZCNT */;
}

void require_host() {
    if (!host_has_required_features()) {
        SKIP("the host CPU lacks AVX2, FMA, BMI1/BMI2, LZCNT, or MOVBE");
    }
}

class Program {
public:
    Program(const char* path, uint64_t base, const cpu::ModuleFunctions& functions)
        : name_(functions.name), base_(base), native_(LoadLibraryA(path)) {
        if (native_ == nullptr) {
            throw std::runtime_error(fmt::format("LoadLibrary failed for {}", path));
        }
        const pe::Image image = pe::Image::load_file(path);
        for (const pe::Export& entry : pe::read_exports(image).exports) {
            if (!entry.name.empty()) {
                exports_.emplace(entry.name, entry.rva);
            }
        }
        g6::kernel::map_image(image, base);
        cpu::register_module(functions);
    }

    std::string_view name() const { return name_; }
    uint64_t base() const { return base_; }
    const std::unordered_map<std::string, uint32_t>& exports() const { return exports_; }

    FARPROC native(const char* symbol) const {
        FARPROC address = GetProcAddress(native_, symbol);
        if (address == nullptr) {
            throw std::runtime_error(fmt::format("{} has no export {}", name_, symbol));
        }
        return address;
    }

    uint64_t guest(const char* symbol) const {
        const auto it = exports_.find(symbol);
        if (it == exports_.end()) {
            throw std::runtime_error(fmt::format("{} has no export {}", name_, symbol));
        }
        return base_ + it->second;
    }

private:
    std::string name_;
    uint64_t base_;
    HMODULE native_;
    std::unordered_map<std::string, uint32_t> exports_;
};

